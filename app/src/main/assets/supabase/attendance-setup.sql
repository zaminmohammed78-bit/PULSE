-- AURAWAY shared teacher-managed attendance
-- Only the internal teacher@auraway.app Supabase Auth identity may write or read
-- the table directly. Students and parents use the read-only code lookup RPC.
-- Run this once in Supabase SQL Editor for the project configured in supabase.js.

create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  student_code text not null,
  attendance_date date not null,
  status text not null check (status in ('Present', 'Absent', 'Leave')),
  marked_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  unique (student_code, attendance_date)
);

alter table public.attendance_records enable row level security;

drop policy if exists "Teachers manage attendance records" on public.attendance_records;
create policy "Teachers manage attendance records"
on public.attendance_records
for all
to authenticated
using ((auth.jwt() ->> 'email') = 'teacher@auraway.app')
with check ((auth.jwt() ->> 'email') = 'teacher@auraway.app');

-- Students/parents use the teacher-issued student code as their lookup credential.
-- This function returns only records matching that exact code; the table itself
-- remains unavailable to anonymous direct SELECT requests.
create or replace function public.get_student_attendance(p_student_code text)
returns table (
  attendance_date date,
  status text
)
language sql
security definer
set search_path = public
as $$
  select ar.attendance_date, ar.status
  from public.attendance_records ar
  where ar.student_code = upper(trim(p_student_code))
  order by ar.attendance_date desc;
$$;

revoke all on function public.get_student_attendance(text) from public;
grant execute on function public.get_student_attendance(text) to anon, authenticated;

grant select, insert, update, delete on public.attendance_records to authenticated;
grant usage, select on sequence public.attendance_records_id_seq to authenticated;
